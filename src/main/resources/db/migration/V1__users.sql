-- V1: accounts (matches the AppUser entity)
-- Written in the SQL both H2 (PostgreSQL mode) and PostgreSQL understand.

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name           VARCHAR(80)  NOT NULL,
    email               VARCHAR(120) NOT NULL,          -- always stored trimmed and lower-case
    password_hash       VARCHAR(100) NOT NULL,          -- BCrypt, never the real password
    role                VARCHAR(20)  NOT NULL,
    enabled             BOOLEAN      NOT NULL DEFAULT TRUE,
    created_on          DATE         NOT NULL DEFAULT CURRENT_DATE,
    storage_quota_bytes BIGINT       NOT NULL DEFAULT 2147483648,  -- Locker limit, 2 GB by default
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role  CHECK (role IN ('TEACHER', 'ADMIN', 'SUPER_ADMIN')),
    CONSTRAINT ck_users_quota CHECK (storage_quota_bytes >= 0)
);
