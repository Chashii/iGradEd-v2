-- V5: departments, tasks given by department heads, and announcements for events and meetings

CREATE TABLE departments (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    CONSTRAINT uq_departments_name UNIQUE (name)
);

-- A teacher or a department head belongs to at most one department.
-- Deleting a department just leaves its people without one.
ALTER TABLE users ADD COLUMN department_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_department
    FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE SET NULL;
CREATE INDEX idx_users_department ON users (department_id);

-- assigned_by NULL = the teacher's own task. Otherwise it was given by that admin.
ALTER TABLE todos ADD COLUMN assigned_by BIGINT;
ALTER TABLE todos ADD CONSTRAINT fk_todos_assigned_by
    FOREIGN KEY (assigned_by) REFERENCES users (id) ON DELETE SET NULL;
CREATE INDEX idx_todos_assigned_by ON todos (assigned_by);

-- department_id NULL = shown to the whole school. event_on = the day the event or meeting happens.
-- Deleting a department deletes the announcements made for it.
ALTER TABLE announcements ADD COLUMN event_on DATE;
ALTER TABLE announcements ADD COLUMN department_id BIGINT;
ALTER TABLE announcements ADD CONSTRAINT fk_announcements_department
    FOREIGN KEY (department_id) REFERENCES departments (id) ON DELETE CASCADE;
CREATE INDEX idx_announcements_department ON announcements (department_id);

-- Add the MEETING kind, and make sure an announcement can't end before it starts
ALTER TABLE announcements DROP CONSTRAINT ck_announcements_kind;
ALTER TABLE announcements ADD CONSTRAINT ck_announcements_kind
    CHECK (kind IN ('NEWS', 'EVENT', 'MEETING', 'URGENT'));
ALTER TABLE announcements ADD CONSTRAINT ck_announcements_dates
    CHECK (expires_on IS NULL OR expires_on >= published_on);
