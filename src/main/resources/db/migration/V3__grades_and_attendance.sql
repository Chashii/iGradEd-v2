-- V3: the Grades and Attendance features

-- Something a teacher scores: a quiz, an exam, a project...
CREATE TABLE assessments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id   BIGINT        NOT NULL REFERENCES classes (id) ON DELETE CASCADE,
    term_id    BIGINT        NOT NULL REFERENCES terms (id),
    title      VARCHAR(100)  NOT NULL,
    category   VARCHAR(20)   NOT NULL,
    max_score  NUMERIC(6, 2) NOT NULL,
    given_on   DATE,
    CONSTRAINT ck_assessments_category CHECK (category IN
        ('QUIZ', 'EXAM', 'ACTIVITY', 'PROJECT', 'RECITATION', 'OTHER')),
    CONSTRAINT ck_assessments_max      CHECK (max_score > 0)
);

CREATE INDEX idx_assessments_class_term ON assessments (class_id, term_id);

-- One student's result on one assessment. No row yet, or a NULL score, means "not graded".
CREATE TABLE scores (
    assessment_id BIGINT NOT NULL REFERENCES assessments (id) ON DELETE CASCADE,
    student_id    BIGINT NOT NULL REFERENCES students (id)    ON DELETE CASCADE,
    score         NUMERIC(6, 2),
    remarks       VARCHAR(200),
    PRIMARY KEY (assessment_id, student_id),
    CONSTRAINT ck_scores_nonneg CHECK (score IS NULL OR score >= 0)
);

CREATE INDEX idx_scores_student ON scores (student_id);

-- One student, one class, one day
CREATE TABLE attendance_records (
    class_id    BIGINT      NOT NULL REFERENCES classes (id)  ON DELETE CASCADE,
    student_id  BIGINT      NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    attended_on DATE        NOT NULL,
    status      VARCHAR(10) NOT NULL,
    note        VARCHAR(200),
    PRIMARY KEY (class_id, student_id, attended_on),
    CONSTRAINT ck_attendance_status CHECK (status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED'))
);

CREATE INDEX idx_attendance_day ON attendance_records (class_id, attended_on);
CREATE INDEX idx_attendance_student ON attendance_records (student_id);
