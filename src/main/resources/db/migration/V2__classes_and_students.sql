-- V2: who teaches what, and who is in each class

-- Grading periods, e.g. school year "2026-2027", name "1st Quarter". Shared by the whole school.
CREATE TABLE terms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_year VARCHAR(9)  NOT NULL,
    name        VARCHAR(40) NOT NULL,
    starts_on   DATE        NOT NULL,
    ends_on     DATE        NOT NULL,
    CONSTRAINT uq_terms       UNIQUE (school_year, name),
    CONSTRAINT ck_terms_dates CHECK (ends_on >= starts_on)
);

-- One row = one subject a teacher handles for one group of students, e.g. "Grade 8 - Rizal" / "Science".
CREATE TABLE classes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id  BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(80) NOT NULL,
    subject     VARCHAR(80) NOT NULL,
    school_year VARCHAR(9)  NOT NULL,
    created_on  DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_classes UNIQUE (teacher_id, school_year, name, subject)
);

CREATE INDEX idx_classes_teacher ON classes (teacher_id);

CREATE TABLE students (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_no VARCHAR(20),                              -- school ID / LRN, optional
    first_name VARCHAR(60) NOT NULL,
    last_name  VARCHAR(60) NOT NULL,
    created_on DATE        NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_students_no UNIQUE (student_no)        -- several students may have no number
);

CREATE INDEX idx_students_name ON students (last_name, first_name);

-- Which students are in which class
CREATE TABLE enrollments (
    class_id    BIGINT NOT NULL REFERENCES classes (id)  ON DELETE CASCADE,
    student_id  BIGINT NOT NULL REFERENCES students (id) ON DELETE CASCADE,
    enrolled_on DATE   NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (class_id, student_id)
);

CREATE INDEX idx_enrollments_student ON enrollments (student_id);
