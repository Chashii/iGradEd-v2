-- V4: Locker files, To-do list and the home page announcements

-- Only the file's details live here. The file itself is saved on disk (or cloud storage) under stored_name.
-- Space used = SUM(size_bytes) for an owner, compared with users.storage_quota_bytes.
CREATE TABLE locker_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    folder        VARCHAR(80)  NOT NULL DEFAULT 'General',
    original_name VARCHAR(255) NOT NULL,                  -- what the teacher called it
    stored_name   VARCHAR(64)  NOT NULL,                  -- random name used on disk
    content_type  VARCHAR(120),
    size_bytes    BIGINT       NOT NULL,
    uploaded_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_locker_stored_name UNIQUE (stored_name),
    CONSTRAINT ck_locker_size        CHECK (size_bytes >= 0)
);

CREATE INDEX idx_locker_owner_folder ON locker_files (owner_id, folder);

CREATE TABLE todos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      VARCHAR(120) NOT NULL,
    due_on     DATE,
    done       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_todos_owner ON todos (owner_id, done);

-- School-wide news shown in the home page banner
CREATE TABLE announcements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         VARCHAR(10)  NOT NULL,
    title        VARCHAR(120) NOT NULL,
    body         VARCHAR(500) NOT NULL,
    published_on DATE         NOT NULL DEFAULT CURRENT_DATE,
    expires_on   DATE,                                    -- NULL = never expires
    created_by   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_announcements_kind CHECK (kind IN ('NEWS', 'EVENT', 'URGENT'))
);

CREATE INDEX idx_announcements_published ON announcements (published_on);
